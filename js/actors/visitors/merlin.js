/* ============================================================================
 * actors/visitors/merlin.js — ЧАРІВНИК МЕРЛІН (легенди про короля Артура)
 * ----------------------------------------------------------------------------
 * Високий ковпак і мантія в зорях, довга сива борода, посох з кристалом.
 * Підходить до Nexi, змахує посохом — і Nexi на 12 с отримує чарівний
 * випадковий колір корпусу (nexi.js -> magic()).
 * ========================================================================== */
NX.visitors.def('merlin', {
  W: 28, H: 48, speed: 30, color: '#7a8aff', outline: [14, 12, 40],
  draw(P, pose, t, v) {
    const RB = '#2a3ab8', RBL = '#4a5ae8', RBD = '#1a2478', BE = '#f0f0f8', SK = '#f0c8a8', ST = '#ffe27a', b = (pose === 'walk' && v.frame % 2) ? 1 : 0, cast = pose === 'cast';
    // мантія до землі
    P(7, 20, 15, 26, RB); P(6, 30, 17, 16, RB); P(7, 20, 15, 1, RBL); P(6, 45, 17, 1, RBD); P(14, 22, 1, 23, RBD);
    [[9, 26], [18, 31], [10, 38], [17, 42], [12, 34]].forEach(([a, c], i) => { P(a, c, 1, 1, ST); if ((i + Math.floor(t * 3)) % 3 === 0) { P(a - 1, c, 3, 1, ST); P(a, c - 1, 1, 3, ST); } });
    P(9, 44 + b, 4, 2, '#3a2a5a'); P(16, 44 - b, 4, 2, '#3a2a5a');
    // посох з кристалом
    const sx = cast ? 24 : 24, sy = cast ? 2 : 8; P(sx, sy + 6, 2, 40 - sy, '#8a5a2a'); P(sx - 1, sy, 4, 6, '#7af0ff'); P(sx, sy + 1, 2, 2, '#ffffff');
    P(22, cast ? 10 : 22, 4, 4, SK); P(19, cast ? 12 : 22, 5, 4, RB); P(4, 23, 4, 9, RB); P(4, 31, 3, 2, SK);
    // голова, борода, ковпак
    P(10, 12, 10, 8, SK); P(11, 15, 2, 1, '#1a1a3a'); P(16, 15, 2, 1, '#1a1a3a'); P(10, 13, 3, 1, BE); P(16, 13, 3, 1, BE);
    P(9, 18, 12, 6, BE); P(10, 24, 10, 4, BE); P(12, 28, 6, 3, BE); P(14, 31, 2, 2, BE); P(13, 18, 4, 1, '#c8c8d8');
    P(7, 10, 16, 3, RB); P(9, 6, 12, 4, RB); P(11, 3, 8, 3, RB); P(13, 0, 4, 3, RB); P(16, 0, 3, 1, RB); P(7, 10, 16, 1, RBL);
    P(12, 6, 1, 1, ST); P(17, 4, 1, 1, ST); P(15, 8, 1, 1, ST);
  },
  script(v) {
    const n = NX.nexi, [x, y] = NX.room.clampWalk(n.x - 40, Math.max(n.y, 384));
    return [{ say: 'hi' }, { walk: [x, y] }, { face: 1 }, { say: 'magic', dur: 2.2 },
      { wait: 1.8, pose: 'cast', tick: (vv, dt) => { if (Math.random() < .6) NX.fx.emit('spark', NX.px.lerp(vv.x + 18, n.x, Math.random()), vv.y - 60 + Math.random() * 30, { col: Math.random() < .5 ? '#7af0ff' : '#ffe27a' }); } },
      { do: () => NX.nexi.magic() }, { wait: 1 }, { say: 'bye' }];
  },
});
