/* ============================================================================
 * objects/ai_desk.js — СТІЛ AI-ЦЕНТРУ (усе намальоване на самій картинці)
 * ----------------------------------------------------------------------------
 * Nexi злітає ранцем на стільницю і друкує на НОУТБУЦІ з картинки.
 * Тут малюється лише "життя" поверх ноутбука: коли this.active, на його
 * екрані друкуються рядки відповіді клієнту, а клавіатура підсвічується.
 * Координати екрана ноутбука — в SCREEN (одиниці кімнати).
 * ========================================================================== */
NX.addObject({
  id: 'aiPc', name: 'obj.aiPc', act: 'ai',
  hit: { x: 60, y: 40, w: 270, h: 262 }, active: false, prog: 0,
  SCREEN: { x: 261, y: 266, w: 18, h: 18 },
  drawBack(c, t) {
    if (!this.active) return;
    const P = NX.px, s = this.SCREEN, lines = Math.min(5, Math.floor(this.prog * 14) + 1);
    P.rect(c, s.x, s.y, s.w, s.h, 'rgba(6,16,46,.85)');
    for (let i = 0; i < lines; i++) { const w = [14, 9, 12, 7, 11][i]; P.rect(c, s.x + 2, s.y + 2 + i * 3.2, i === lines - 1 ? w * ((t * 3) % 1) : w, 1.5, i % 2 ? '#ff7af0' : '#7af0ff'); }
    if (this.prog > .8) P.rect(c, s.x + 11, s.y + 13, 5, 3, '#3bff8a');                         // "надіслано"
    P.glow(c, s.x + s.w / 2, s.y + s.h / 2, 22, 'rgba(59,232,255,.6)', .6);
    for (let i = 0; i < 6; i++) if (((t * 14 + i * 5) | 0) % 3 === 0) P.rect(c, 258 + i * 4, 293, 2.5, 1, '#7af0ff');   // клавіші
  },
});
