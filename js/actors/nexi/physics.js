/* ============================================================================
 * actors/nexi/physics.js — "ФІЗИКА" NEXI (пружини, нахил, стискання)
 * ----------------------------------------------------------------------------
 * Робить рухи живими, не змінюючи сам спрайт:
 *   lean  – нахил тіла в бік руху (розганяється / гальмує, як справжній)
 *   ax/ay – пружне погойдування кінчика антени (відстає від руху й тремтить)
 *   sq    – стискання/розтягування: присідає перед стрибком, "сплющується"
 *           при приземленні, а потім пружинить назад
 *   look  – куди дивляться очі (роззирається, коли нудьгує)
 * Значення передаються в позу (nexi.js -> layer()) і в трансформацію малювання.
 * ========================================================================== */
NX.phys = {
  /** Пружина: o[key] тягнеться до target зі швидкістю o[key+'V'] (k — жорсткість, damp — згасання). */
  spring(o, key, target, k, damp, dt) { const v = key + 'V'; o[v] = (o[v] || 0) + ((target - o[key]) * k - o[v] * damp) * dt; o[key] += o[v] * dt; },
};
NX.nexiPhys = {
  px: null, py: null, vx: 0, vy: 0, lean: 0, ax: 0, ay: 0, sq: 1,
  update(n, dt) {
    if (this.px === null) { this.px = n.x; this.py = n.y; }
    const d = Math.max(dt, 1e-3), ivx = (n.x - this.px) / d, ivy = (n.y - this.py) / d; this.px = n.x; this.py = n.y;
    this.vx += (ivx - this.vx) * Math.min(1, dt * 10); this.vy += (ivy - this.vy) * Math.min(1, dt * 10);
    const S = NX.phys.spring, C = NX.px.clamp;
    S(this, 'lean', C(this.vx / NX.cfg.RUN_SPEED * 10, -12, 12), 70, 10, dt);       // нахил у бік руху
    S(this, 'ax', C(-this.vx * .04, -4, 4), 110, 3.5, dt);                           // антена відстає і тремтить
    S(this, 'ay', C(this.vy * .025, -3, 3), 110, 4, dt);
    S(this, 'sq', 1, 190, 11, dt);                                                    // повернення форми
  },
  land(p = 3) { this.sqV = -p; },        // приземлення: сплющитись
  kick(p = 2.5) { this.sqV = p; },       // стрибок: витягнутись
};
