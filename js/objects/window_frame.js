/* ============================================================================
 * objects/window_frame.js — ПЕРЕХІД СТІНА → ВІКНО З ДВОХ БОКІВ (дзеркальні відкоси)
 * ----------------------------------------------------------------------------
 * Власник: «зроби перехід від стіни до вікна, такий як з правої сторони; хай вони дзеркальні
 * будуть; можеш відразу з двох сторін». Раніше ліворуч цегла просто обривалась рожевою
 * трубкою, а праворуч на картинці був розмитий відкос. Тепер обидва боки — ОДИН растр кодом:
 *   ліворуч він стоїть біля стіни крила (x 534..), праворуч — точне дзеркало (..970) поверх
 *   розмитого відкосу картинки (обрізаний там, де попереду стоїть машинерія майстерні).
 * Відкіс (від стіни до скла, локальна координата u = 0..26):
 *   u 0..11  — лицьова стійка: темний фіолет, світлий край біля стіни, шви панелей з болтами,
 *              вертикальна фаска й паз, вогники-індикатори (живі)
 *   u 11..14 — рожева неонова трубка на хромованих хомутах (дихає, світить на стійку й відкіс)
 *   u 14..26 — відкіс (бічна грань віконного прорізу): освітлений трубкою фіолетовий перелив,
 *              шви йдуть у перспективі до точки сходу кімнати; біля скла — блакитний кант
 *   угорі    — косинка-підсилювач у куті (як справа на картинці) з блакитним неоном по скосу
 * Растр 4 px/од. будується раз; щокадру — дві копії (одна дзеркальна) + світіння трубок і вогники.
 * Малюється після стіни крила й до будки маркетингу (вона стоїть перед лівим відкосом).
 * ========================================================================== */
(() => {
  const P = NX.px, F = NX.furn, K = NX.kit, { CHROME, OUT } = F.PAL, ramp = F.ramp, rgba = K.rgba, lit = K.lit;
  const H = 284, W = 40;                                                         // растр у локальних одиницях: u 0..40, y 0..284
  const L = 534, R = 970;                                                        // зовнішні краї (біля стіни): лівий відкіс u -> L + u, правий u -> R - u
  const PF = ['#07041a', '#0d0829', '#140c3a', '#1c114c', '#251660', '#301c76', '#3c248c', '#4a2ea2'];   // лицьова стійка
  const REV = ['#0a0a3a', '#10124e', '#181c66', '#222880', '#30329c', '#4236b6', '#5a3ec8', '#7444d8', '#9050e4'];   // відкіс, освітлений трубкою
  const SEAM0 = 20, SEAM = 48;                                                   // шви панелей
  const VPK = .053;                                                              // наскільки шви відкосу «тікають» до точки сходу (VP y 220) на його ширині
  const CLAMPS = [62, 132, 202, 262];                                            // хромовані хомути трубки
  const LEDS = [[5.5, 96, '59,232,255'], [5.5, 150, '255,79,216'], [5.5, 214, '59,232,255']];
  // правий відкіс картинки закриває машинерія майстерні: там, де вона починається, наш растр обрізаємо
  const R_STOP = [[925, 954.5, 180.5], [954.5, 975, 176.5]];

  function build() {
    const S = F.Sheet(0, 0, W, H);
    // ---- лицьова стійка (u 0..11)
    S.rect(0, 0, 11, H, (u, v, i, j, X, Y) => {
      if (X < .8) return ramp(['#2e2280', '#4a38aa', '#6a52cc', '#8a6ae0'], .55 + .3 * (1 - Y / H), i, j);   // світлий край біля стіни
      if (X < 1.4 || X > 10.3) return '#0a0620';
      const sy = ((Y - SEAM0) % SEAM + SEAM) % SEAM;
      if (sy < .6) return '#05031a'; if (sy < 1.1) return '#3c248c';                                   // шов панелі: щілина + світла кромка
      if (X > 2.1 && X < 2.7) return '#3a2492';                                                         // фаска
      if (X > 8.5 && X < 9.1) return '#0b0726';                                                         // паз
      const q = .2 + (X / 10.3) ** 2 * .34 + (1 - Y / H) * .07 + (sy < 5 ? .05 : 0);                   // ближче до трубки — світліше
      return ramp(PF, q, i, j, .1);
    });
    for (let y = SEAM0 + 5; y < H - 6; y += SEAM) for (const bx of [4.4, 7.4]) S.rr(bx - .9, y - .9, bx + .9, y + .9, .9, (d, u, v, i, j) => d < .3 ? OUT : u < .45 && v < .45 ? CHROME[4] : CHROME[2]);   // болти
    // ---- відкіс (u 14..26): перелив від трубки до скла, шви в перспективі, блакитний кант біля скла
    S.rect(14, 0, 26, H, (u, v, i, j, X, Y) => {
      const k = VPK * (X - 14) / 12, y0 = (Y - 220 * k) / (1 - k), sy = ((y0 - SEAM0) % SEAM + SEAM) % SEAM;   // «рівень» точки на передній кромці (шви сходяться до VP)
      if (X > 25.2) return Y < 72 ? (X > 25.6 ? '#9af6ff' : '#3be8ff') : (X > 25.6 ? '#3be8ff' : '#17709a');   // кант біля скла (угорі яскравіший)
      if (sy < .7) return '#0a0838'; if (sy < 1.3) return '#5a46c8';
      let q = .86 - (X - 14) / 11.2 * .8 + (sy < 6 ? .06 : 0);
      const col = ramp(REV, q, i, j, .12);
      return X > 21.5 && Y > 70 && Y < 230 ? K.mix(col, '#1a5ab8', Math.min(.35, (X - 21.5) / 4 * .35)) : col;   // біля скла — холодний відсвіт міста
    });
    // ---- неонова трубка (u 11..14) на хомутах
    S.rect(11, 0, 14, H, (u, v, i, j, X) => X < 11.35 || X > 13.65 ? OUT : (X < 11.9 || X > 13.1) ? '#ff4fd8' : '#ffc2ec');
    CLAMPS.forEach(y => S.rr(10.5, y, 14.5, y + 2.2, .5, (d, u, v, i, j) => d < .3 ? OUT : v < .35 ? CHROME[4] : ramp(CHROME, .55 - v * .3, i, j)));
    // ---- косинка в куті (як на картинці справа): плита зі скосом, блакитний неон по скосу, болт
    S.poly([[11.2, 0], [38.6, 0], [26, 36], [14, 36], [14, 6], [11.2, 6]], (u, v, i, j, X, Y) => {
      const e = 38.6 - (38.6 - 26) * (Y / 36) - X;                                                         // відстань до скосу
      if (e < 1.6) return e < .5 ? '#9af6ff' : '#3be8ff';
      if (e < 2.3) return '#0a0620';
      return ramp(PF, .42 + (Y < 6 ? .12 : 0) - Y / 36 * .14, i, j, .08);
    });
    S.rect(0, 0, 38.8, 1.8, (u, v, i, j) => ramp(['#1c114c', '#2e1c6c', '#4a2ea2'], .7 - v * .5, i, j));     // верхня планка (стик зі стелею)
    S.poly([[19.4, 9], [22, 7.6], [24.6, 9], [24.6, 12], [22, 13.4], [19.4, 12]], (u, v, i, j) => u < .5 && v < .5 ? CHROME[4] : CHROME[2]);   // шестигранний болт
    return S;
  }
  // м'яке світіння трубки (кешоване полотно: горизонтальний перелив, однаковий для обох відкосів)
  let GL = null;
  function glowStrip() {
    const cv = document.createElement('canvas'); cv.width = 64; cv.height = 4; const x = cv.getContext('2d'), g = x.createLinearGradient(0, 0, 64, 0);
    g.addColorStop(0, 'rgba(255,79,216,0)'); g.addColorStop(.38, 'rgba(255,79,216,.55)'); g.addColorStop(.5, 'rgba(255,150,236,.9)'); g.addColorStop(.62, 'rgba(255,79,216,.55)'); g.addColorStop(1, 'rgba(255,79,216,0)');
    x.fillStyle = g; x.fillRect(0, 0, 64, 4); return cv;
  }
  let SH = null;
  /** Один відкіс: растр + живе (світіння трубки, неон косинки, вогники). mirror — правий. */
  function jamb(c, t, mirror, stopY) {
    const Rr = F.res();
    c.save();
    if (mirror) { c.translate(R, 0); c.scale(-1, 1); } else c.translate(L, 0);
    c.imageSmoothingEnabled = Rr < 3.8; c.drawImage(F.fit(SH.cv, W, H, Rr), 0, 0, W, H);
    c.globalCompositeOperation = 'lighter';
    const br = .17 + .06 * Math.sin(t * 1.3 + (mirror ? 1.7 : 0)) + .02 * Math.sin(t * 7.1);
    c.globalAlpha = br; c.imageSmoothingEnabled = true; c.drawImage(GL, 5.5, 2, 14, stopY - 2);                // трубка світить на стійку й відкіс
    c.globalAlpha = 1;
    P.glow(c, 31, 17, 13, 'rgba(59,232,255,.85)', .16 + .05 * Math.sin(t * 1.7 + (mirror ? 2 : 0)));          // неон косинки
    CLAMPS.forEach((y, n) => { if (y < stopY - 3) P.glow(c, 12.5, y + 1.1, 4, 'rgba(255,200,240,.9)', .12 + .05 * Math.sin(t * 2 + n)); });
    LEDS.forEach(([x, y, rgb], n) => { if (y > stopY - 4) return; const on = .35 + .65 * (Math.sin(t * (1.1 + n * .37) + n * 2 + (mirror ? 1 : 0)) > .2); lit(c, x - .45, y - .45, .9, .9, rgba(rgb, on)); P.glow(c, x, y, 3, `rgba(${rgb},.9)`, .14 * on); });
    c.restore();
  }
  NX.addObject({
    id: 'windowFrame',
    drawBack(c, t) {
      if (!SH) { SH = build(); SH.cv = SH.canvas(); GL = glowStrip(); }
      jamb(c, t, false, H);                                                      // лівий — біля стіни крила (низ ховається за будкою й столом маркетингу)
      c.save(); c.beginPath(); R_STOP.forEach(([a, b, y]) => c.rect(a, -2, b - a, y + 2)); c.clip();              // правий — до машинерії майстерні
      jamb(c, t, true, 182);
      const g = c.createLinearGradient(0, 166, 0, 181); g.addColorStop(0, 'rgba(4,2,16,0)'); g.addColorStop(1, 'rgba(4,2,16,.55)'); c.fillStyle = g; c.fillRect(930, 166, 42, 15);   // тінь від машинерії
      c.restore();
    },
  });
})();
