/* ============================================================================
 * actors/visitors/kolobok.js — КОЛОБОК (народна казка)
 * ----------------------------------------------------------------------------
 * Рум'яний колобок котиться по кімнаті ("Я від баби втік!"), Рудик ганяється
 * за ним. Обертання імітуємо зсувом рум'янця й очей по кадрах.
 * ========================================================================== */
NX.visitors.def('kolobok', {
  W: 16, H: 16, speed: 60, pxs: .85, color: '#ffd02a', outline: [60, 30, 6],
  draw(P, pose, t, v) {
    const Y = '#f0b040', YL = '#ffd878', YD = '#c07a20', roll = pose === 'walk' || pose === 'run' ? v.frame % 4 : 0;
    P(4, 1, 8, 14, Y); P(2, 3, 12, 10, Y); P(1, 5, 14, 6, Y); P(4, 1, 8, 1, YL); P(3, 3, 3, 2, YL); P(4, 14, 8, 1, YD); P(14, 6, 1, 5, YD);
    const fx = [0, 2, 0, -2][roll], fy = [0, 1, 2, 1][roll];
    P(5 + fx, 5 + fy, 2, 2, '#2a1a0a'); P(10 + fx, 5 + fy, 2, 2, '#2a1a0a'); P(5 + fx, 5 + fy, 1, 1, '#ffffff'); P(10 + fx, 5 + fy, 1, 1, '#ffffff');
    P(6 + fx, 9 + fy, 5, 1, '#8a2a1a'); P(5 + fx, 8 + fy, 1, 1, '#8a2a1a'); P(11 + fx, 8 + fy, 1, 1, '#8a2a1a');
    P(3 + fx, 8 + fy, 2, 1, '#ff8a6a'); P(12 + fx, 8 + fy, 2, 1, '#ff8a6a');
  },
  script(v) {
    const s = [{ say: 'hi' }];
    for (let i = 0; i < 4; i++) { const p = NX.visitors.spot(); s.push({ walk: p, run: true, do: () => { if (i < 3) NX.cat.goTo(p[0] - 18, p[1], () => NX.cat.set('pounce', .5), null, true); } }); }
    s.push({ say: 'bye' }); return s;
  },
});
