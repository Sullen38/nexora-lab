/* ============================================================================
 * objects/coffee.js — КАВОМАШИНА (біля столів, між аналітикою і маркетингом)
 * ----------------------------------------------------------------------------
 * this.brew 0..1 — прогрес варіння. Під час варіння: тече кава, йде пара,
 * на дисплеї "BREW". Nexi натискає кнопки (поза press), потім п'є (drink).
 * ========================================================================== */
NX.addObject({
  id: 'coffee', name: 'Кавомашина', act: 'coffee',
  hit: { x: 486, y: 298, w: 48, h: 56 }, brew: 0, cup: false,
  update(dt, t) { if (this.brew > 0 && this.brew < 1) { this.brew = Math.min(1, this.brew + dt / 3); if (Math.random() < .3) NX.fx.emit('steam', 506 + Math.random() * 4, 334); } },
  layers(t) { return [{ y: 349, draw: c => this.draw(c, t) }]; },
  draw(c, t) {
    const P = NX.px, b = this.brew, on = b > 0 && b < 1;
    P.cube(c, 491, 349, 34, 46, 6, '#2a2f5e', '#3e4588', '#1a1d40');
    P.rect(c, 491, 303, 34, 1, '#ff4fd8');                                                    // неонова окантовка
    P.rect(c, 496, 308, 24, 9, '#06102e'); P.text(c, on ? 'BREW' : b >= 1 ? 'DONE' : 'NEXI', 498, 315, on ? '#ffe27a' : '#3be8ff', 3.5);
    [0, 1, 2].forEach(i => P.rect(c, 498 + i * 7, 320, 4, 2, on && Math.floor(t * 6) % 3 === i ? '#3bff8a' : '#4a55a0'));
    P.rect(c, 497, 326, 22, 17, '#0e1030'); P.rect(c, 503, 324, 10, 3, '#5a6590');            // ніша і носик
    if (on) P.rect(c, 507, 327, 2, 10, '#7a4a22');                                            // струмінь кави
    if (on || this.cup) { P.rect(c, 504, 337, 8, 6, '#ffffff'); P.rect(c, 512, 338, 2, 3, '#ffffff'); P.rect(c, 505, 337, 6, 1, '#7a4a22'); }
    P.rect(c, 495, 343, 26, 2, '#5a6590');                                                    // піддон
    P.glow(c, 508, 312, 18, 'rgba(59,232,255,.4)', .4);
  },
});
