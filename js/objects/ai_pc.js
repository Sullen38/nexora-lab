/* ============================================================================
 * objects/ai_pc.js — КОМП'ЮТЕР AI-ЦЕНТРУ (на лівому столі)
 * ----------------------------------------------------------------------------
 * Монітор + системний блок + клавіатура + голограма "мозку" над монітором.
 * Nexi злітає ранцем на стільницю, стає праворуч і друкує (activities.js → ai).
 * this.active = true  -> на екрані друкується код/відповідь клієнту
 * this.active = false -> заставка NEXORA
 * ========================================================================== */
NX.addObject({
  id: 'aiPc', name: "AI-центр · комп'ютер", act: 'ai',
  hit: { x: 60, y: 40, w: 200, h: 262 }, active: false, prog: 0,
  layers(t) { return [{ y: 296.4, draw: c => this.draw(c, t) }]; },
  draw(c, t) {
    const P = NX.px, on = this.active;
    // голограма над монітором (щільна основа, щоб не просвічувала стіна)
    P.rect(c, 150, 214, 44, 28, '#06102ee6'); P.holo(c, 150, 214, 44, 28, on ? '#ff7af0' : '#3be8ff', t, 1);
    const br = ['.XXXX.', 'XX.XXX', 'XXXX.X', 'X.XXXX', '.XXXX.'];
    br.forEach((r, j) => [...r].forEach((ch, i) => { if (ch === 'X') P.rect(c, 157 + i * 3, 219 + j * 3, 3, 3, (i + j + Math.floor(t * 4)) % 5 ? (on ? '#ff7af0' : '#3be8ff') : '#fff'); }));
    for (let i = 0; i < 3; i++) P.rect(c, 178, 220 + i * 6, on ? 10 + 4 * Math.sin(t * 5 + i) : 10, 2, '#9af6ff');
    P.rect(c, 170, 242, 4, 4, '#3be8ff55');                                                         // промінь проектора
    // монітор
    P.rect(c, 146, 246, 52, 38, '#1a1f4a'); P.rect(c, 146, 246, 52, 2, '#3a4290'); P.rect(c, 149, 249, 46, 32, '#06102e');
    if (on) {                                                                                          // друк коду
      const lines = Math.floor(this.prog * 12) + 1;
      for (let i = 0; i < Math.min(8, lines); i++) { const w = [30, 22, 36, 18, 28, 34, 20, 26][(i + Math.floor(lines / 8) * 3) % 8]; P.rect(c, 152, 252 + i * 3.5, i === Math.min(7, lines - 1) ? w * ((t * 3) % 1) : w, 2, i % 3 ? '#3be8ff' : '#ff7af0'); }
      if (Math.floor(t * 3) % 2) P.rect(c, 152, 252 + Math.min(7, lines - 1) * 3.5, 2, 2, '#fff');
    } else { const bx = 152 + (Math.sin(t * .8) * .5 + .5) * 18, by = 255 + (Math.cos(t * .6) * .5 + .5) * 18; P.text(c, 'NEXORA', bx, by, '#3be8ff', 3.5); }
    P.glow(c, 172, 265, 30, on ? 'rgba(255,120,240,.5)' : 'rgba(59,232,255,.4)', .5);
    P.rect(c, 168, 284, 8, 8, '#2a2f5e'); P.rect(c, 160, 292, 24, 4, '#2a2f5e');                     // підставка
    P.cube(c, 128, 297, 12, 30, 6, '#1d2150', '#2e3478', '#141838');                                 // системний блок
    P.rect(c, 131, 272, 6, 1, on ? '#3bff8a' : '#2a6a4a'); P.rect(c, 131, 276, 6, 1, '#3be8ff');
    P.cube(c, 152, 298, 50, 2, 4, '#2a2f5e', '#3e4588', '#1a1d40');                                  // клавіатура
    for (let i = 0; i < 11; i++) P.rect(c, 155 + i * 4.3, 294, 3, 1.5, on && ((t * 14 + i * 5) | 0) % 3 === 0 ? '#3be8ff' : '#4a55a0');
  },
});
