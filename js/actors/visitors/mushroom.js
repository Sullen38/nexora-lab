/* ============================================================================
 * actors/visitors/mushroom.js — ГРИБОЧОК (власний персонаж Nexora)
 * ----------------------------------------------------------------------------
 * Неоново-фіолетовий капелюшок зі світними цятками, милий ротик, ніжки.
 * Пострибує по кімнаті. ТАП -> Nexi біжить і з'їдає його, і з ним стається
 * щось випадкове (nexi.js -> eatEffect): райдужний, крихітний, запаморочення,
 * іскри щастя або супершвидкість. Якщо не з'їсти — сам повернеться в портал.
 * ========================================================================== */
NX.visitors.def('mushroom', {
  W: 18, H: 20, speed: 30, pxs: .8, color: '#ff7af0', outline: [36, 10, 44],
  draw(P, pose, t, v) {
    const hop = pose === 'walk' ? Math.abs(Math.sin(t * 8)) * 2 | 0 : 0, y = 0 - hop, C = '#b02ad8', CL = '#e86aff', CD = '#7a1a98', DOT = Math.sin(t * 4) > 0 ? '#7af0ff' : '#c8faff';
    P(5, 18, 3, 2, '#7a4a8a'); P(10, 18, 3, 2, '#7a4a8a');                                                     // ніжки
    P(5, 10 + y, 8, 8, '#fff0e0'); P(5, 10 + y, 1, 8, '#ffffff'); P(12, 10 + y, 1, 8, '#e0c8b0');               // ніжка-тіло
    P(6, 13 + y, 1, 2, '#2a1020'); P(11, 13 + y, 1, 2, '#2a1020'); P(6, 13 + y, 1, 1, '#ffffff'); P(8, 16 + y, 2, 1, '#c8282e'); P(5, 15 + y, 1, 1, '#ff9fb5'); P(12, 15 + y, 1, 1, '#ff9fb5');
    P(2, 6 + y, 14, 4, C); P(1, 7 + y, 16, 3, C); P(4, 3 + y, 10, 3, C); P(6, 2 + y, 6, 1, C); P(5, 3 + y, 6, 1, CL); P(3, 5 + y, 3, 1, CL); P(1, 9 + y, 16, 1, CD);   // капелюшок
    [[4, 5], [9, 3], [13, 6], [7, 7]].forEach(([a, b2]) => P(a, b2 + y, 2, 2, DOT));
  },
  script(v) {
    const s = [{ say: 'hi' }]; for (let i = 0; i < 3; i++) s.push({ walk: NX.visitors.spot() }, { wait: 1.2 });
    s.push({ say: 'bye' }); return s;
  },
  tap(v) { NX.visitors.say(v, 'eatme'); v.queue = []; v.cur = { wait: 99, _t: 0 }; NX.nexi.eatMushroom(v); },
});
