/* ============================================================================
 * actors/visitors/babayaga.js — БАБА ЯГА В СТУПІ (народна казка)
 * ----------------------------------------------------------------------------
 * Вилітає з порталу в ступі, з мітлою, червона хустка. Робить кілька
 * кіл над кімнатою, змітає за собою слід пилу, сміється "Хі-хі-хі!".
 * ========================================================================== */
NX.visitors.def('babayaga', {
  W: 34, H: 42, speed: 40, flySpeed: 95, color: '#ff9a3a', outline: [30, 16, 10],
  draw(P, pose, t, v) {
    const SK = '#e8c0a0', SKD = '#b88a68', SC = '#c8282e', SCL = '#ff5a5e', WD = '#7a5a3a', WDL = '#a07a50', WDD = '#4a3420', sw = Math.round(Math.sin(t * 10) * 2);
    // мітла (віник за ступою)
    P(28 + sw, 10, 2, 24, '#8a6a3a'); for (let i = 0; i < 6; i++) P(26 + i + sw, 33 + (i % 2), 1, 7, i % 2 ? '#d8b060' : '#b89040');
    // ступа
    P(6, 26, 22, 4, WDL); P(7, 30, 20, 6, WD); P(9, 36, 16, 3, WD); P(11, 39, 12, 2, WDD); P(6, 26, 22, 1, '#c8a070');
    for (let i = 0; i < 4; i++) P(9 + i * 5, 30, 1, 8, WDD);
    // тіло: кофта, руки тримають мітлу
    P(10, 17, 14, 10, '#5a3a7a'); P(10, 17, 14, 1, '#7a5a9a'); P(22, 18, 6, 3, '#5a3a7a'); P(26, 17, 3, 3, SK);
    P(7, 18, 4, 6, '#5a3a7a'); P(6, 23, 3, 2, SK);
    // голова: хустка, довгий ніс, зуб
    P(11, 6, 12, 11, SK); P(11, 6, 12, 1, '#ffd8c0'); P(10, 3, 14, 6, SC); P(9, 5, 2, 9, SC); P(23, 5, 2, 9, SC); P(10, 3, 14, 1, SCL); P(14, 2, 6, 1, SC);
    for (let i = 0; i < 4; i++) P(11 + i * 3, 5, 1, 1, '#ffffff');                                      // горошок на хустці
    P(8, 14, 4, 4, SC); P(22, 14, 3, 4, SC);                                                          // кінці хустки
    P(13, 9, 2, 2, '#1a1a1a'); P(18, 9, 2, 2, '#1a1a1a'); P(13, 9, 1, 1, '#ffffff'); P(18, 9, 1, 1, '#ffffff');
    P(22, 10, 4, 2, SKD); P(25, 11, 2, 2, SKD); P(15, 14, 5, 1, '#5a1a1a'); P(16, 15, 1, 1, '#ffffff');   // ніс, усмішка із зубом
    P(11, 15, 1, 2, '#c8c8c8'); P(23, 15, 1, 2, '#c8c8c8');                                             // сиве пасмо
  },
  script(v) {
    const s = [{ say: 'hi' }];
    for (let i = 0; i < 4; i++) { const [x, y] = NX.visitors.spot(); s.push({ fly: [x, y], alt: 40 + Math.random() * 45 }); if (i === 1) s.push({ say: 'laugh' }); }
    s.push({ fly: [NX.nexi.x, Math.max(NX.nexi.y, 384)], alt: 60, do: () => NX.nexi.emote('surprise', 2) }, { say: 'bye' });
    return s;
  },
});
// пил з-під мітли, поки вона летить
(() => { const u = NX.visitors.step.bind(NX.visitors); NX.visitors.step = function (v, dt) { u(v, dt); if (v.def.id === 'babayaga' && v.alt > 10 && Math.random() < .6) NX.fx.emit('dust', v.x + (v.dir > 0 ? -16 : 16), v.y - v.alt + 2); }; })();
