/* ============================================================================
 * actors/visitors/leprechaun.js — ЛЕПРЕКОН (ірландський фольклор)
 * ----------------------------------------------------------------------------
 * Маленький чоловічок у зеленому сюртуку й капелюсі з золотою пряжкою,
 * руда борода, горщик із золотом. Ходить кімнатою й ГУБИТЬ МОНЕТКИ
 * (objects/coins.js) — Nexi їх збирає. Тап по ньому -> висипає ще 3.
 * ========================================================================== */
NX.visitors.def('leprechaun', {
  W: 22, H: 32, speed: 40, pxs: .78, color: '#3bff8a', outline: [10, 30, 14],
  draw(P, pose, t, v) {
    const G = '#2a9a4a', GL = '#4ac86a', GD = '#1a6a30', SK = '#f2c8a0', BE = '#e8702a', BEL = '#ffa050', GO = '#ffd02a', b = (pose === 'walk' && v.frame % 2) ? 1 : 0;
    NX.visitors.legs(P, v, pose, 7, 12, 26, 4, '#2a2a1a', '#1a1208'); P(6, 30, 5, 1, GO); P(11, 30, 5, 1, GO);   // черевики з пряжками
    P(5, 16 - b, 12, 11, G); P(5, 16 - b, 12, 1, GL); P(10, 17 - b, 2, 9, GD); P(5, 23 - b, 12, 2, '#1a1208'); P(10, 23 - b, 2, 2, GO);   // сюртук, пояс
    const sw = pose === 'walk' ? (v.frame % 2 ? 1 : -1) : 0;
    P(2, 17 + sw, 3, 7, G); P(17, 17 - sw, 3, 7, G); P(2, 24 + sw, 3, 2, SK);
    P(16, 22 - sw, 6, 6, '#3a3a40'); P(16, 22 - sw, 6, 1, '#5a5a60'); P(17, 21 - sw, 4, 1, GO); if (Math.floor(t * 4) % 2) P(18, 20 - sw, 1, 1, '#fff2a0');   // горщик золота
    P(6, 6 - b, 10, 10, SK); P(6, 6 - b, 10, 1, '#ffe0c0'); P(8, 9 - b, 2, 1, '#1a1a1a'); P(12, 9 - b, 2, 1, '#1a1a1a'); P(11, 10 - b, 2, 2, '#e8a080');
    P(5, 11 - b, 12, 6, BE); P(6, 16 - b, 10, 2, BE); P(8, 18 - b, 6, 1, BE); P(5, 11 - b, 12, 1, BEL); P(9, 12 - b, 4, 1, '#c84a3a');   // руда борода, усмішка
    P(4, 4 - b, 14, 2, GD); P(6, -0 - b + 0, 10, 5, G); P(6, 0, 10, 1, GL); P(6, 3 - b, 10, 1, '#1a1208'); P(10, 3 - b, 3, 1, GO);           // капелюх з пряжкою
    P(16, 2 - b, 3, 3, GL); P(17, 1 - b, 1, 1, '#ffffff');                                                                              // конюшинка
  },
  script(v) {
    const s = [{ say: 'hi' }];
    for (let i = 0; i < 4; i++) s.push({ walk: NX.visitors.spot(), do: vv => { NX.objects.coins.drop(vv.x, vv.y); NX.objects.coins.drop(vv.x + 4, vv.y + 2); } }, { wait: .5, do: vv => i === 1 && NX.visitors.say(vv, 'oops') });
    s.push({ say: 'bye' }); return s;
  },
  tap(v) { NX.visitors.say(v, 'oops'); for (let i = 0; i < 3; i++) NX.objects.coins.drop(v.x + (Math.random() - .5) * 16, v.y + 2); },
});
