/* ============================================================================
 * objects/plants_front.js — ВЕЛИКІ РОСЛИНИ НА ПЕРЕДНЬОМУ ПЛАНІ
 * ----------------------------------------------------------------------------
 * Стоять у кутах, найближче до глядача (малюються останніми), листя трохи
 * гойдається. Дають відчуття глибини кімнати.
 * ========================================================================== */
NX.addObject({
  id: 'plants', name: 'Рослини',
  layers(t) {
    const H = 368 + NX.cam.front, P = NX.px;
    const plant = (c, px, flip) => {
      const leaves = [[-.9, 70], [-.5, 92], [-.2, 104], [.15, 98], [.5, 86], [.85, 70], [-.7, 56], [.7, 60]];
      leaves.forEach(([a0, len], i) => {
        const a = a0 + Math.sin(t * 1.1 + i) * .04, col = ['#1f6a4a', '#2f9a62', '#3fbf7a', '#1a4a3a'][i % 4];
        for (let s = 0; s < len; s += 2) { const tt = s / len, w = Math.round((1 - Math.abs(tt - .45) * 1.6) * 9) + 2; P.rect(c, px + Math.sin(a * flip) * s + flip * tt * tt * 18 * a - w / 2, H - 44 - Math.cos(a) * s + tt * tt * 24, w, 2, col); }
      });
      P.cube(c, px - 22, H + 4, 44, 40, 10, '#2a1c60', '#4b32a0', '#1b1244'); P.rect(c, px - 22, H - 36, 44, 2, '#ff4fd8');
    };
    return [{ y: 1e6, draw: c => { plant(c, 34, 1); plant(c, NX.cfg.ROOM_W - 44, -1); } }];
  },
});
