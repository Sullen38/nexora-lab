/* ============================================================================
 * core/persp.js — ПЕРСПЕКТИВА КІМНАТИ (NX.persp)
 * ----------------------------------------------------------------------------
 * Картинка кімнати — в ОДНОТОЧКОВІЙ перспективі: усі лінії вглиб сходяться в точці VP (774, 220) — центр вікна, там же
 * центр дивану. Одна перспектива на все: 3D-рушій (core/px3d.js), крила й зони (objects/arc_scene.js), живі шари.
 *
 * Світ: x — вправо, y — вниз (як у кімнаті), z — углиб (0 = площина картинки); око — (774, 220, −D).
 *   VP, D                — точка сходу й відстань до ока (520)
 *   s(z) = D / (D + z)   — у скільки разів менше на глибині z;  zOf(k) — глибина за масштабом k
 *   p(x, y, z) -> [X, Y] — точка світу -> координати кімнати
 * Старі інструменти 2D-меблів (box — коробка в растр, wall — картинка на стіні смужками, desk — інша точка сходу) —
 * в історії git (коміт a431f03).
 * ========================================================================== */
NX.persp = (() => {
  const VP = [774, 220], D = 520;
  const s = z => D / (D + z), zOf = k => D / k - D;
  const p = (x, y, z) => { const k = s(z); return [VP[0] + (x - VP[0]) * k, VP[1] + (y - VP[1]) * k]; };
  return { VP, D, s, zOf, p };
})();
