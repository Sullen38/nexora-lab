/* ============================================================================
 * core/namespace.js — ГЛОБАЛЬНИЙ ПРОСТІР ІМЕН
 * ----------------------------------------------------------------------------
 * Увесь проєкт живе в одному об'єкті window.NX, щоб модулі не змішувались
 * з іншим кодом сторінки. Кожен файл додає сюди свій блок:
 *   NX.cfg      – константи (core/config.js)
 *   NX.px       – піксельні інструменти малювання (core/pixel.js)
 *   NX.cam      – камера, масштаб, перетягування (core/camera.js)
 *   NX.room     – кімната: фон, стеля, передня підлога (world/room.js)
 *   NX.ambient  – "життя" ще не перемальованої картинки: екрани, лампи (world/ambient.js)
 *   NX.city     – панорамне вікно: місто за склом кодом (world/cityscape.js; інструменти —
 *                 NX.ckit city_kit.js, небо й планета — NX.citySky, хмарочоси — NX.cityBuild)
 *   NX.objects  – інтерактивні об'єкти кімнати (js/objects/*.js)
 *   NX.nexi     – бот Nexi (js/actors/nexi/*.js)
 *   NX.cat      – рудий кіт (js/actors/cat/*.js)
 *   NX.fx       – частинки (js/fx/particles.js)
 *   NX.ui       – інтерфейс поверх сцени (js/ui/*.js)
 * Технології: чистий JavaScript (ES2020) + HTML5 Canvas 2D. Без фреймворків
 * і без збірки: index.html просто підключає файли по черзі.
 * ========================================================================== */
window.NX = {
  objects: {},      // реєстр об'єктів кімнати: NX.objects[id] = {...}
  ui: {},
  time: 0,          // поточний час сцени в секундах
  /** Реєстрація об'єкта кімнати. Кожен об'єкт — окремий незалежний блок. */
  addObject(obj) { this.objects[obj.id] = obj; return obj; },
};
